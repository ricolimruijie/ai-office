// Copy the event contract from the backend repo into shared/. The backend owns it, so never edit the copies.
// Usage: npm run sync-contract            (expects ../ai-office-backend)
//        BACKEND_DIR=/path/to/backend npm run sync-contract
import { copyFileSync, readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const backend = resolve(process.env.BACKEND_DIR || resolve(root, "../ai-office-backend"));
const FILES = ["events.ts", "mentions.ts"];
const BANNER = "/* GENERATED by `npm run sync-contract` from ai-office-backend/contract. Do not edit here. */\n";

for (const f of FILES) {
  const src = resolve(backend, "contract", f);
  let text;
  try { text = readFileSync(src, "utf8"); } catch { console.error("Cannot read " + src + ". Set BACKEND_DIR."); process.exit(1); }
  text = text.replace(/^\/\* Shared contract\..*\*\/\n/, "");
  writeFileSync(resolve(root, "shared", f), BANNER + text);
  console.log("synced shared/" + f);
}
